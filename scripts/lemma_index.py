#!/usr/bin/env python3
"""Regenerate docs/LEMMA_INDEX.md from the Tamarin sources and results.txt.

Why this exists: the paper claims a set of properties per model, and the
repository had no machine-readable index of which lemma lives where, of which
kind (all-traces vs exists-trace), and whether the recorded run verified it.
Keeping the index generated (not hand-written) means it cannot silently drift
from the sources.

Usage:  python3 scripts/lemma_index.py            # write docs/LEMMA_INDEX.md
        python3 scripts/lemma_index.py --check    # fail if the file is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = [
    ("GOD", "GOD"),
    ("fairness", "fairness"),
    ("sec_with_abort", "sec_with_abort"),
    ("semi_honest", "semi_honest"),
    ("complexity 2 parties", "complexity_measures/2_party"),
    ("complexity 3 parties", "complexity_measures/3_party"),
    ("complexity 4 parties", "complexity_measures/4_party"),
]
OUT = ROOT / "docs" / "LEMMA_INDEX.md"

LEMMA_RE = re.compile(r"^\s*lemma\s+([A-Za-z0-9_]+)\s*(\[[^\]]*\])?\s*:")
RESULT_RE = re.compile(r"^\s{2}([A-Za-z0-9_]+)\s+\((all-traces|exists-trace)\):\s+(verified|falsified)")
RUN_RE = re.compile(r'Command being timed: "tamarin-prover (\S+) --prove"')
TIME_RE = re.compile(r"processing time:\s*([0-9.]+)s")


def parse_lemmas(path: Path) -> list[dict]:
    """Return [{name, kind, file}] for every lemma in one .spthy file."""
    lines = path.read_text(encoding="utf-8").splitlines()
    out = []
    for i, line in enumerate(lines):
        m = LEMMA_RE.match(line)
        if not m:
            continue
        name, attrs = m.group(1), (m.group(2) or "")
        # the kind marker sits either in the attribute list or right after the colon
        tail = attrs
        for nxt in lines[i + 1 : i + 4]:
            tail += " " + nxt
            if '"' in nxt:
                break
        kind = "exists-trace" if "exists-trace" in tail else "all-traces"
        out.append({"name": name, "kind": kind, "file": path.name})
    return out


def parse_results(path: Path) -> dict[str, dict]:
    """Map model path -> {'time': float, 'lemmas': {name: status}}.

    results.txt stores, for each run, the lemma verdicts first and the
    '/usr/bin/time' report (with the command line) afterwards, so verdicts are
    attributed to the run named by the NEXT 'Command being timed' line.
    """
    runs: list[dict] = []
    cur = {"lemmas": {}, "time": None}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = RUN_RE.search(line)
        if m:
            cur["model"] = m.group(1).lstrip("./")
            runs.append(cur)
            cur = {"lemmas": {}, "time": None}
            continue
        t = TIME_RE.search(line)
        if t and cur["time"] is None and not cur["lemmas"]:
            cur["time"] = float(t.group(1))
        r = RESULT_RE.match(line)
        if r:
            cur["lemmas"][r.group(1)] = r.group(3)
    if cur["lemmas"] and "model" not in cur:
        cur["model"] = None  # trailing block without a run header
    return {r["model"]: r for r in runs if r.get("model")}


def build() -> str:
    results = parse_results(ROOT / "results.txt") if (ROOT / "results.txt").exists() else {}
    lines = [
        "# Lemma index",
        "",
        "Generated by `scripts/lemma_index.py` — do not edit by hand.",
        "Regenerate with `python3 scripts/lemma_index.py`.",
        "",
        "`all-traces` = property must hold on every trace; `exists-trace` = the",
        "trace class must be reachable (reachability / attributability check).",
        "",
        "## Models",
        "",
        "| Model | dir | lemmas | all-traces | exists-trace | recorded run |",
        "|---|---|---:|---:|---:|---|",
    ]
    per_model: dict[str, list[dict]] = {}
    for label, rel in MODELS:
        lemmas: list[dict] = []
        for f in sorted((ROOT / rel).glob("*.spthy")):
            lemmas.extend(parse_lemmas(f))
        per_model[rel] = lemmas
        n_all = sum(1 for x in lemmas if x["kind"] == "all-traces")
        n_ex = len(lemmas) - n_all
        run = results.get(f"{rel}/MPC.spthy")
        if run and run["time"]:
            rec = f"{run['time']:.2f} s ({len(run['lemmas'])} lemmas reported)"
        elif run:
            rec = f"verdicts only ({len(run['lemmas'])} lemmas)"
        else:
            rec = "— (no run recorded in results.txt)"
        lines.append(f"| {label} | `{rel}/` | {len(lemmas)} | {n_all} | {n_ex} | {rec} |")

    lines += ["", "## Lemma names per model", ""]
    for label, rel in MODELS:
        lines.append(f"### {label} (`{rel}/`)")
        lines.append("")
        lines.append("| lemma | kind | file | verdict in results.txt |")
        lines.append("|---|---|---|---|")
        run = results.get(f"{rel}/MPC.spthy", {"lemmas": {}})["lemmas"]
        for lm in per_model[rel]:
            verdict = run.get(lm["name"], "not reported")
            lines.append(f"| `{lm['name']}` | {lm['kind']} | {lm['file']} | {verdict} |")
        lines.append("")

    # drift check: verdicts reported for lemmas that no longer exist in the sources
    drift = []
    for rel, run in results.items():
        model_dir = (ROOT / rel).parent
        known = set()
        if model_dir.is_dir():
            for f in sorted(model_dir.glob("*.spthy")):
                known |= {x["name"] for x in parse_lemmas(f)}
        for name in run["lemmas"]:
            if name not in known:
                drift.append((rel, name))
    lines += ["## Drift", ""]
    if drift:
        lines.append("Verdicts recorded for lemma names that do not exist in the current sources:")
        lines.append("")
        for rel, name in drift:
            lines.append(f"- `{rel}`: `{name}`")
        lines += [
            "",
            "Either rename the lemma back, or re-run the model and refresh `results.txt`;",
            "until then the recorded verdict cannot be attributed to the current source.",
        ]
    else:
        lines.append("None — every recorded verdict matches a lemma in the sources.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/LEMMA_INDEX.md is stale — run python3 scripts/lemma_index.py", file=sys.stderr)
            return 1
        print("docs/LEMMA_INDEX.md is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
